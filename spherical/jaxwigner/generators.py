"""Exact derivatives of 𝔇 with respect to the rotor, from the Lie algebra.

The forward computations factor 𝔇 into sin β and the phases e^{iα}, e^{iγ},
which are undefined at the poles β = 0, π.  The singular parts cancel in the
values but not in automatic derivatives, which are wrong there.  𝔇 itself is a
smooth (polynomial) function of the quaternion, and its derivative is simple:
for a change δR,

    R + ε δR = R (1 + ε R⁻¹ δR) ≈ (1 + εσ) R exp(ε ω),   σ + ω ≔ R̄ δR / |R|²,

with σ a scalar and ω = (ωx, ωy, ωz) a vector.  Scaling does not change 𝔇, and
𝔇(R exp(ε ω)) = 𝔇(R) 𝔇(exp(ε ω)), so

    δ𝔇ˡ = 𝔇ˡ(R) Gˡ,   Gˡ = 2 (ωx Λˡx + ωy Λˡy + ωz Λˡz),

where Λˡₖ = d/dε 𝔇ˡ(exp(ε eₖ/2)) at ε = 0 are fixed tridiagonal matrices.  In
the conventions of `spherical`, with c(m) = ½√((ℓ-m)(ℓ+m+1)),

    (Λz)_{m,m} = i m,
    (Λx)_{m,m+1} = (Λx)_{m+1,m} = i c(m),
    (Λy)_{m,m+1} = c(m),   (Λy)_{m+1,m} = -c(m).

(These were read off from finite differences of 𝔇 and are verified by the
tests.)  Multiplying a row vector F by Gˡ on the right gives

    (F G)ₘ = 2 [ i m ωz Fₘ + (iωx + ωy) c(m-1) Fₘ₋₁ + (iωx - ωy) c(m) Fₘ₊₁ ].

For harmonics, ₛYₗₘ ∝ 𝔇ˡ_{m,-s}, multiplying by G on the right mixes the column
-s with its neighbors -s∓1, i.e. with harmonics of spin weight s±1:

    δ(ₛYₗₘ) = 2 [ -i s ωz ₛYₗₘ - (iωx + ωy) c(-s-1) ₛ₊₁Yₗₘ - (iωx - ωy) c(-s) ₛ₋₁Yₗₘ ].

All of these are exact at every rotor, including the poles, and are linear in
δR, so JAX can transpose them for reverse-mode differentiation.

"""

from functools import lru_cache
import math

import numpy as np
import jax.numpy as jnp

from .quaternions import multiply, conjugate


def c(ell, m):
    """½√((ℓ-m)(ℓ+m+1)), which vanishes at m = ℓ and m = -ℓ-1."""
    return 0.5 * math.sqrt(max((ell - m) * (ell + m + 1), 0))


def omega(R, δR):
    """(ωx, ωy, ωz): the vector part of R̄ δR / |R|², the rotation generated by δR."""
    R = jnp.asarray(R)
    q = multiply(conjugate(R), δR) / jnp.sum(R * R, axis=-1, keepdims=True)
    return q[..., 1], q[..., 2], q[..., 3]


@lru_cache(maxsize=None)
def _right_action_tables(ell_m_pairs):
    """(m, c(m-1), c(m)) for each (ℓ, m) in a flat layout, as float arrays."""
    m = np.array([m for _, m in ell_m_pairs], dtype=float)
    c_minus = np.array([c(ell, m - 1) for ell, m in ell_m_pairs])
    c_plus = np.array([c(ell, m) for ell, m in ell_m_pairs])
    return m, c_minus, c_plus


@lru_cache(maxsize=None)
def mode_layout(ell_min, ell_max):
    """(ℓ, m) for each entry of the mode-weight / sYlm layout."""
    return tuple((ell, m) for ell in range(ell_min, ell_max + 1) for m in range(-ell, ell + 1))


@lru_cache(maxsize=None)
def D_layout(ell_min, ell_max):
    """(ℓ, m) for each entry of the flat 𝔇 layout; m is the second (column) index."""
    return tuple(
        (ell, m)
        for ell in range(ell_min, ell_max + 1)
        for mp in range(-ell, ell + 1)
        for m in range(-ell, ell + 1)
    )


def apply_right_generator(F, ω, ell_m_pairs):
    """F Gˡ for each ℓ block, acting on the last axis, whose entries are labelled by
    `ell_m_pairs`.  Neighbors Fₘ±₁ are taken from the adjacent flat entries; at the
    ends of each run of m values their coefficients c are exactly zero, so the
    entries read across run boundaries never contribute.
    """
    m, c_minus, c_plus = _right_action_tables(ell_m_pairs)
    real = jnp.real(F).dtype
    m, c_minus, c_plus = (jnp.asarray(x, dtype=real) for x in (m, c_minus, c_plus))
    ωx, ωy, ωz = (w[..., None] for w in ω)
    pad = [(0, 0)] * (F.ndim - 1)
    F_previous = jnp.pad(F[..., :-1], pad + [(1, 0)])  # Fₘ₋₁
    F_next = jnp.pad(F[..., 1:], pad + [(0, 1)])  # Fₘ₊₁
    return 2 * (
        1j * ωz * m * F
        + (1j * ωx + ωy) * c_minus * F_previous
        + (1j * ωx - ωy) * c_plus * F_next
    )


@lru_cache(maxsize=None)
def spin_mixing_coefficients(s, ell_min, ell_max):
    """(c(-s-1), c(-s)) for each (ℓ, m) of the mode layout, as float arrays."""
    pairs = mode_layout(ell_min, ell_max)
    return (
        np.array([c(ell, -s - 1) for ell, _ in pairs]),
        np.array([c(ell, -s) for ell, _ in pairs]),
    )


def sYlm_tangent(s, Y, Y_raised, Y_lowered, ω, ell_min, ell_max):
    """δ(ₛYₗₘ) given ₛY, ₛ₊₁Y and ₛ₋₁Y, all in the mode layout."""
    c_raise, c_lower = spin_mixing_coefficients(s, ell_min, ell_max)
    real = jnp.real(Y).dtype
    c_raise, c_lower = jnp.asarray(c_raise, dtype=real), jnp.asarray(c_lower, dtype=real)
    ωx, ωy, ωz = (w[..., None] for w in ω)
    return 2 * (
        -1j * s * ωz * Y
        - (1j * ωx + ωy) * c_raise * Y_raised
        - (1j * ωx - ωy) * c_lower * Y_lowered
    )
